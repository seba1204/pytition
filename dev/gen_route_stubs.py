#!/usr/bin/env python3
"""
Generate mypy `.pyi` stubs enforcing a 1–1 mapping for Enum-based routes.

This tool scans every `routes.py` under `src/apps/**/routes.py` and emits a
`urls_contract.pyi` stub in the same directory, containing a `Protocol` that
lists one attribute per enum member. In each `urls.py`, binding a dynamically
built object to that `Protocol` nudges mypy to flag missing attributes when
stubs are up-to-date.

Workflow
--------
- Run on save via a file-watcher (e.g., VS Code) whenever a `routes.py` or
  `urls.py` changes.
- Commit generated stubs so CI and mypy on other machines see them too.

Limitations
-----------
Mypy cannot guarantee dictionary key totality from runtime data alone.
This stub-based approach is a pragmatic compromise: if the enum changes and
stubs are regenerated, mypy will complain until `urls.py` maps all members.

Usage
-----
$ python dev/gen_route_stubs.py
$ python dev/gen_route_stubs.py --files src/apps/organizations/routes.py
"""

from __future__ import annotations

import argparse
import ast
from collections.abc import Iterable
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
APPS_DIR = PROJECT_ROOT / "src" / "apps"
STUB_FILENAME = "urls_contract.pyi"


def _is_namespaced_route_base(base: ast.expr) -> bool:
    """Return True if a class base refers to `NamespacedRoute` (by simple or dotted
    name)."""
    if isinstance(base, ast.Name):
        return base.id == "NamespacedRoute"
    if isinstance(base, ast.Attribute):
        parts: list[str] = []
        cur: ast.expr = base
        while isinstance(cur, ast.Attribute):
            parts.append(cur.attr)
            cur = cur.value  # type: ignore[assignment]
        if isinstance(cur, ast.Name):
            parts.append(cur.id)
        dotted = ".".join(reversed(parts))
        return dotted.endswith("NamespacedRoute")
    return False


def _extract_enum_members(cls: ast.ClassDef) -> list[str]:
    """Extract upper cased enum member names assigned to a string or a single-item tuple
    of a string, preserving declaration order."""
    members: list[str] = []
    for node in cls.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name) and target.id.isupper():
                val = node.value
                if (
                    isinstance(val, ast.Constant)
                    and isinstance(val.value, str)
                    or (
                        isinstance(val, ast.Tuple)
                        and len(val.elts) == 1
                        and isinstance(val.elts[0], ast.Constant)
                        and isinstance(val.elts[0].value, str)
                    )
                ):
                    members.append(target.id)
    return members


def find_route_enums(routes_py: Path) -> list[tuple[str, list[str]]]:
    """Parse a `routes.py` file and return a list of (EnumName, [MEMBER,...])."""
    text = routes_py.read_text(encoding="utf-8")
    tree = ast.parse(text, filename=str(routes_py))
    enums: list[tuple[str, list[str]]] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and any(
            _is_namespaced_route_base(b) for b in node.bases
        ):
            members = _extract_enum_members(node)
            if members:
                enums.append((node.name, members))
    return enums


STUB_HEADER = """# AUTO-GENERATED FILE — DO NOT EDIT.
# Generated by dev/gen_route_stubs.py from {routes_rel}
from typing import Protocol
from apps.core.routes import Route

"""

CLASS_TEMPLATE = """class {enum_name}UrlsContract(Protocol):
{body}
"""

ATTR_TEMPLATE = "    {member}: Route\n"


def generate_stub_for_routes(routes_py: Path) -> dict[Path, str]:
    """
    Generate one `urls_contract.pyi` for the given `routes.py`, if it contains one or
    more `NamespacedRoute` subclasses.

    Returns
    -------
    dict
        Mapping of output stub path to its textual content.
    """
    enums = find_route_enums(routes_py)
    if not enums:
        return {}

    rel = routes_py.relative_to(PROJECT_ROOT).as_posix()
    content_parts: list[str] = [STUB_HEADER.format(routes_rel=rel)]
    for enum_name, members in enums:
        body = "".join(ATTR_TEMPLATE.format(member=m) for m in members)
        content_parts.append(CLASS_TEMPLATE.format(enum_name=enum_name, body=body))
    stub_text = "".join(content_parts)

    out_path = routes_py.parent / STUB_FILENAME
    return {out_path: stub_text}


def iter_routes_files(specific: Iterable[str] | None) -> list[Path]:
    """Find route definition files to process."""
    if specific:
        files: list[Path] = []
        for s in specific:
            p = Path(s).resolve()
            if p.is_dir():
                files.extend(p.rglob("routes.py"))
            elif p.name == "routes.py":
                files.append(p)
        return files
    return list(APPS_DIR.rglob("routes.py"))


def main() -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--files",
        nargs="*",
        help="Optional subset of routes.py files (or directories) to process.",
    )
    args = parser.parse_args()

    wrote = 0
    for routes_py in iter_routes_files(args.files):
        mapping = generate_stub_for_routes(routes_py)
        for out_path, text in mapping.items():
            out_path.write_text(text, encoding="utf-8")
            rel = out_path.relative_to(PROJECT_ROOT).as_posix()
            print(f"[gen-route-stubs] wrote {rel}")
            wrote += 1
    if wrote == 0:
        print("[gen-route-stubs] no stubs generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
